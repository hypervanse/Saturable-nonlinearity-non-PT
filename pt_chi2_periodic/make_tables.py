"""
make_tables.py -- LaTeX tables for the manuscript, written straight from results/*.json
(no number in these tables is typed by hand).  Output: manuscript/tables/*.tex
  validation.tex   building-block checks            (results/validation.json, results/weak.json)
  thirdgap.tex     third-gap branches: extent and growth window   (results/thirdgap.json)
  convergence.tex  third-gap growth rates vs h, L and absorber    (results/convergence.json)
"""
import os
from io_utils import load

OUT = 'manuscript/tables'
os.makedirs(OUT, exist_ok=True)
GTOL, REMAX = 5e-5, 3.0                      # same classification as make_figures.py
IMRE, IMG = 0.05, 1e-3                       # weak purely imaginary near-edge modes: box artefacts


def sci(v, d=2):
    """1.23e-04 -> 1.23\\times10^{-4} (math mode)"""
    if v is None or v == 0:
        return '0'
    m, e = f"{v:.{d}e}".split('e')
    return f"{m}\\times10^{{{int(e)}}}"


def num(v, d=4):
    return f"{v:.{d}f}".replace('-', '-')


def arnoldi_row():
    """largest |growth(Arnoldi target) - growth(dense)| over the test solitons of validate_arnoldi.py"""
    if not os.path.exists('results/arnoldi.json'):
        return "(run validate\\_arnoldi.py)"
    A = load('results/arnoldi.json')['rows']
    d = max(abs(r['target']['g'] - r['dense']['g']) for r in A)
    ds = max(abs(r['scan']['g'] - r['dense']['g']) for r in A)
    if d == 0 and ds == 0:                       # results files keep 6 significant digits
        return "identical to the 6 stored significant digits (one shift and scan)"
    return f"max $|\\Delta\\,\\mathrm{{Im}}\\,\\lambda|$: ${sci(d)}$ (target), ${sci(ds)}$ (scan)"


# ---- validation -----------------------------------------------------------------------------
V, W = load('results/validation.json'), load('results/weak.json')
rk = V['rk45']
sp = V['spline']
nw = [r for r in V['newton'] if r['deriv'] == 'fd4']
fo = [r for r in V['newton'] if r['deriv'] == 'fourier']
import math
p_sp = math.log(sp[-2]['err'] / sp[-1]['err'], 2)
p_fd = [math.log(abs(nw[i]['P'] - fo[-1]['P']) / abs(nw[i + 1]['P'] - fo[-1]['P']), nw[i]['h'] / nw[i + 1]['h'])
        for i in range(len(nw) - 1)]
so = V['ssf_order']
rows = [
    (r"RKF4(5), $y''=-y$ to $\xi=20\pi$", f"$\\mathrm{{rtol}}=10^{{-12}}$: error ${sci(rk[-1]['err'])}$, "
     f"{rk[-1]['nacc']} accepted / {rk[-1]['nrej']} rejected steps"),
    (r"clamped cubic spline", f"observed order {p_sp:.2f}"),
    (r"SH band edge $b_{2+}^{(0)}$ vs Mathieu $-a_0(2)/4$", f"${V['bands']['sh_top']:.6f}$ vs ${V['bands']['mathieu']:.6f}$"),
    (r"Newton, 4th-order differences", "observed order " + ", ".join(f"{p:.2f}" for p in p_fd)),
    (r"Newton, Fourier: $P$ for $h=0.30,0.20,0.15$", ", ".join(f"{r['P']:.8f}" for r in fo)),
    (r"shooting vs Newton, $\max|w_1|$ difference", f"${sci(fo[-1]['shoot_vs_newton'])}$"),
    (r"analytic vs finite-difference Jacobian", f"${sci(V['jacobian_rel_err'])}$ (relative)"),
    (r"split-step, stationary state to $\zeta=10$", f"drift ${sci(V['ssf_stationary'])}$"),
    (r"split-step order (Strang / Yoshida)", f"{so['2']['order']:.2f} / {so['4']['order']:.2f}" if 'order' in so['2'] else "see validation.json"),
    (r"growth rate: $\mathrm{Im}\,\lambda$ vs propagation (case 1, $b=0.5$)",
     f"{V['growth']['eig'][1]:.4f} vs {V['growth']['ssf_rate']:.4f}"),
    (r"shift-invert Arnoldi vs dense spectrum (6 solitons)", arnoldi_row()),
    (r"weak: case 3, $b=0.21$", f"${sci(W['case3_b0.21']['lam'][1])}$ vs ${sci(W['case3_b0.21']['ssf_rate'])}$"),
    (r"weak: third gap, $\alpha=0.7919$, $b=-1.207$", f"${sci(W['gap3_b-1.207']['lam'][1])}$ vs ${sci(W['gap3_b-1.207']['ssf_rate'])}$"),
]
with open(f'{OUT}/validation.tex', 'w') as f:
    f.write("% generated by make_tables.py from results/validation.json, results/weak.json -- do not edit\n")
    f.write("\\begin{tabular}{ll}\n\\hline\\hline\ncheck & result\\\\\n\\hline\n")
    for a, b in rows:
        f.write(f"{a} & {b}\\\\\n")
    f.write("\\hline\\hline\n\\end{tabular}\n")
print('validation.tex')

# ---- third-gap branches ---------------------------------------------------------------------
T = load('results/thirdgap.json')
with open(f'{OUT}/thirdgap.tex', 'w') as f:
    f.write("% generated by make_tables.py from results/thirdgap.json -- do not edit\n")
    f.write("\\begin{tabular}{cccccc}\n\\hline\\hline\n"
            "$\\alpha$ & edge $b_{\\rm e}$ & traced $b$ & $P$ & unstable points & $\\max\\mathrm{Im}\\,\\lambda$\\\\\n\\hline\n")
    for key, e in T['branches'].items():
        pts = sorted(e['points'], key=lambda r: r['b'])
        st = [p for p in pts if p.get('gmax') is not None]
        un = [p for p in st if p['gmax'] > GTOL and abs(p['lam_unst'][0]) < REMAX
              and not (abs(p['lam_unst'][0]) < IMRE and p['gmax'] < IMG)]
        gr = (f"${sci(min(p['gmax'] for p in un), 1)}$--${max(p['gmax'] for p in un):.3f}$" if un else '--')
        f.write(f"{key} & ${e['edge']:.4f}$ & $[{pts[0]['b']:.3f},\\,{pts[-1]['b']:.3f}]$ & "
                f"${min(p['P'] for p in pts):.3f}$--${max(p['P'] for p in pts):.2f}$ & "
                f"{len(un)}/{len(st)} & {gr}\\\\\n")
    f.write("\\hline\\hline\n\\end{tabular}\n")
print('thirdgap.tex')

# ---- convergence ----------------------------------------------------------------------------
if os.path.exists('results/convergence.json'):
    C = load('results/convergence.json')
    rows = C['rows']
    targets = [tuple(t) for t in C['targets']]
    grids = [tuple(gd) for gd in C['grids']]
    with open(f'{OUT}/convergence.tex', 'w') as f:
        f.write("% generated by make_tables.py from results/convergence.json -- do not edit\n")
        f.write("\\begin{tabular}{cc" + "c" * len(grids) + "c}\n\\hline\\hline\n")
        f.write("$\\alpha$ & $b$ & " + " & ".join(f"$L={Lp}\\pi$, $h={h}$" for Lp, h in grids)
                + " & $|\\mathrm{Re}\\,\\lambda|$\\\\\n\\hline\n")
        for al, b in targets:
            cells, re = [], None
            for Lp, h in grids:
                r = [x for x in rows if x['al'] == al and x['b'] == b and x['L_pi'] == Lp and x['h'] == h]
                if not r:
                    cells.append('--')
                    continue
                r = r[0]
                cells.append(f"${sci(r['g_1.0'])}$ (${sci(r['g_0.25'])}$)")
                if r['lam_1.0'] is not None:
                    re = abs(r['lam_1.0'][0])
            f.write(f"{al} & ${b:.3f}$ & " + " & ".join(cells) + f" & ${re:.3f}$\\\\\n" if re is not None
                    else f"{al} & ${b:.3f}$ & " + " & ".join(cells) + " & --\\\\\n")
        f.write("\\hline\\hline\n\\end{tabular}\n")
    print('convergence.tex')
else:
    with open(f'{OUT}/convergence.tex', 'w') as f:
        f.write("% results/convergence.json not found: run run_convergence.py, then make_tables.py\n"
                "\\textit{(pending: run \\texttt{run\\_convergence.py})}\n")
    print('convergence.tex (placeholder)')
